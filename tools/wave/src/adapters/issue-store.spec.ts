// ── classifyCreateInput — the whole-input create contract (ADR-0027, #278/#309)
//
// These are the LAYER specs: the classifier is called directly, with no store
// and no CLI in the picture at all, because that is the claim under test — the
// create-shape invariants are properties of this function, so every caller
// (every adapter's `create()`, the issue-store CLI, any future driver) inherits
// them rather than re-deriving one of them at its own edge.
describe('classifyCreateInput (ADR-0027) — shape classification', () => {
  const BARE: CreateInput = {
    title: 'Gate 8 ships inert',
    filingHint: 'gate-8-ships-inert',
    bodySections: [
      { heading: 'Gap', markdown: 'the verify config is never threaded through.' },
      { heading: 'Provenance', markdown: 'wave hardening, row 3, iteration 1.' },
    ],
  };

  const DECORATED: CreateInput = {
    title: 'A real slice',
    filingHint: 'a-real-slice',
    risk: 'mechanical',
    worker: 'background',
    files: ['src/x.ts'],
    blockedBy: 'none',
    acceptanceCriteria: [{ text: 'does the thing', checked: false }],
  };

  it('classifies a bare input (title + filingHint + authored bodySections) as bare', () => {
    expect(classifyCreateInput(BARE)).toEqual({ kind: 'bare' });
  });

  it('classifies a full Header-Block as decorated and hands back the narrowed input', () => {
    const shape = classifyCreateInput(DECORATED);
    expect(shape.kind).toBe('decorated');
    if (shape.kind === 'decorated') expect(shape.input.risk).toBe('mechanical');
  });

  // The negative control for the bare-body rule below: `bodySections` is
  // optional for a DECORATED input and must STAY optional — a decorated issue
  // has a Header-Block, so it is never a 0-body-char filing. If the requirement
  // ever leaks out of the bare branch, this is the case that fails.
  it('a DECORATED input with NO bodySections is still classified, not rejected', () => {
    expect(DECORATED.bodySections).toBeUndefined();
    expect(classifyCreateInput(DECORATED).kind).toBe('decorated');
    expect(classifyCreateInput({ ...DECORATED, bodySections: [] }).kind).toBe('decorated');
    expect(
      classifyCreateInput({
        ...DECORATED,
        bodySections: [{ heading: 'What to build', markdown: '   ' }],
      }).kind,
    ).toBe('decorated');
  });
});

// The typed rejection below is PUBLIC API as of issue #325: `CreateInputError`
// and `CreateInputFailure` are re-exported from the package root. Its pairing —
// same class binding across the barrel, so a root consumer's `instanceof` matches
// what these adapters throw — is asserted in `index.spec.ts`, the file that owns
// pairings spanning more than one module. These stay the LAYER specs: what the
// classifier rejects and why, with no barrel in the picture.
describe('classifyCreateInput — typed rejections (#309: the classifier owns the invariant)', () => {
  /** Run the classifier and return the CreateInputError it threw. */
  function rejectionOf(input: CreateInput): CreateInputError {
    try {
      classifyCreateInput(input);
    } catch (err) {
      expect(err).toBeInstanceOf(CreateInputError);
      return err as CreateInputError;
    }
    throw new Error('expected classifyCreateInput to reject, but it returned');
  }

  const TITLE = { title: 'Gate 8 ships inert', filingHint: 'gate-8-ships-inert' };

  it('a BARE input with bodySections ABSENT is rejected as `bare-without-body`', () => {
    const err = rejectionOf({ ...TITLE });
    expect(err.failure).toBe('bare-without-body');
    expect(err.fields).toEqual(['bodySections']);
    expect(err.code).toBe('create-input-invalid');
    expect(err.name).toBe('CreateInputError');
  });

  it('a BARE input with bodySections `[]` is rejected the same way', () => {
    expect(rejectionOf({ ...TITLE, bodySections: [] }).failure).toBe('bare-without-body');
  });

  it('a BARE input whose bodySections markdown is ALL BLANK is rejected the same way', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [
        { heading: 'Gap', markdown: '   ' },
        { heading: 'Provenance', markdown: '' },
      ],
    });
    expect(err.failure).toBe('bare-without-body');
  });

  it('ONE non-blank section is enough — the rule asks for authored content, not for every section to carry it', () => {
    expect(
      classifyCreateInput({
        ...TITLE,
        bodySections: [
          { heading: 'Gap', markdown: '   ' },
          { heading: 'Provenance', markdown: 'wave hardening, row 3, iteration 1.' },
        ],
      }),
    ).toEqual({ kind: 'bare' });
  });

  // Message quality is what the CLI renders; the rejection is what it routes on.
  // Both are pinned here so the layer move cannot quietly degrade the operator-
  // facing text into a bare "invalid input".
  it('the bare-body message names the field to fix and what would otherwise be filed', () => {
    const message = rejectionOf({ ...TITLE }).message;
    expect(message).toContain('bodySections');
    expect(message).toContain('no body at all');
    expect(message).toContain('Header-Block');
  });

  it('a HALF-WRITTEN Header-Block is rejected as `header-block-half-written`, naming the missing fields', () => {
    const err = rejectionOf({ ...TITLE, risk: 'mechanical' });
    expect(err.failure).toBe('header-block-half-written');
    expect(err.fields).toEqual(['worker', 'files', 'blockedBy', 'acceptanceCriteria']);
    expect(err.message).toMatch(/half-written/i);
  });

  it('a decoration-only stowaway on a bare input is rejected as `bare-carries-decoration-only-fields`', () => {
    const err = rejectionOf({ ...TITLE, parent: 'some-prd-id' });
    expect(err.failure).toBe('bare-carries-decoration-only-fields');
    expect(err.fields).toEqual(['parent']);
  });

  // Precedence: the stowaway verdict is the more specific claim about a
  // bodyless bare input, so it must not be masked by the body rule.
  it('a bodyless bare input carrying a stowaway reports the stowaway, not the missing body', () => {
    expect(rejectionOf({ ...TITLE, unblocks: [{ issue: 7 }] }).failure).toBe(
      'bare-carries-decoration-only-fields',
    );
  });

  it('every rejection is a real Error subclass (catchable by generic handlers too)', () => {
    const err = rejectionOf({ ...TITLE });
    expect(err).toBeInstanceOf(Error);
    expect(err.stack).toBeTruthy();
  });
});

// #530: a bare bodySections entry that is present but MALFORMED — a missing
// heading, a missing markdown, a blank heading, or a non-string value — used
// to sail past classification (markdown present and non-blank is enough for
// `hasBareBodyContent` to call the input non-empty) and crash three frames
// later inside a tracker adapter's serializer with a raw, un-teaching
// `TypeError: Cannot read properties of undefined (reading 'trim')`. These
// specs pin the typed, teaching refusal in its place — the SAME
// `bare-without-body` discriminant an absent/empty/all-blank `bodySections`
// already throws (the fix direction's "same teaching shape the
// missing-bodySections error already has"), distinguished by `err.fields`
// (a dotted per-entry path here, plain `['bodySections']` there) rather than
// by a new public union member.
describe('classifyCreateInput — a malformed bodySections entry on a BARE input (#530)', () => {
  function rejectionOf(input: CreateInput): CreateInputError {
    try {
      classifyCreateInput(input);
    } catch (err) {
      expect(err).toBeInstanceOf(CreateInputError);
      return err as CreateInputError;
    }
    throw new Error('expected classifyCreateInput to reject, but it returned');
  }

  const TITLE = { title: 'Gate 8 ships inert', filingHint: 'gate-8-ships-inert' };

  it('an entry missing `heading` (markdown present) is refused — no TypeError, nothing filed', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [
        { markdown: 'the verify config is never threaded through.' } as unknown as {
          heading: string;
          markdown: string;
        },
      ],
    });
    expect(err.failure).toBe('bare-without-body');
    expect(err.fields).toEqual(['bodySections[0].heading']);
    expect(err.code).toBe('create-input-invalid');
  });

  it('an entry missing `markdown` (heading present) is refused the same way', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [
        { heading: 'Gap' } as unknown as { heading: string; markdown: string },
      ],
    });
    expect(err.failure).toBe('bare-without-body');
    expect(err.fields).toEqual(['bodySections[0].markdown']);
  });

  it('an entry with a BLANK (whitespace-only) heading is refused', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [{ heading: '   ', markdown: 'authored prose here.' }],
    });
    expect(err.failure).toBe('bare-without-body');
    expect(err.fields).toEqual(['bodySections[0].heading']);
  });

  it('a non-string heading value is refused (not just an absent one)', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [
        { heading: 42, markdown: 'authored prose here.' } as unknown as {
          heading: string;
          markdown: string;
        },
      ],
    });
    expect(err.failure).toBe('bare-without-body');
    expect(err.fields).toEqual(['bodySections[0].heading']);
  });

  it('a non-string markdown value is refused (not just an absent one)', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [
        { heading: 'Gap', markdown: null } as unknown as {
          heading: string;
          markdown: string;
        },
      ],
    });
    expect(err.failure).toBe('bare-without-body');
    expect(err.fields).toEqual(['bodySections[0].markdown']);
  });

  it('both fields malformed in the same entry are named together', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [{ heading: '', markdown: undefined } as unknown as {
        heading: string;
        markdown: string;
      }],
    });
    expect(err.fields).toEqual(['bodySections[0].heading', 'bodySections[0].markdown']);
  });

  it('names the offending entry INDEX when the malformed entry is not the first', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [
        { heading: 'Gap', markdown: 'fine.' },
        { markdown: 'this one is missing its heading.' } as unknown as {
          heading: string;
          markdown: string;
        },
      ],
    });
    expect(err.fields).toEqual(['bodySections[1].heading']);
  });

  it('the message names the entry, the offending field, and the expected entry shape', () => {
    const message = rejectionOf({
      ...TITLE,
      bodySections: [
        { markdown: 'the verify config is never threaded through.' } as unknown as {
          heading: string;
          markdown: string;
        },
      ],
    }).message;
    expect(message).toContain('bodySections[0]');
    expect(message).toContain('heading');
    expect(message).toContain('{ heading: string, markdown: string }');
  });

  it('a well-formed multi-entry bare input is NOT rejected (negative control)', () => {
    expect(
      classifyCreateInput({
        ...TITLE,
        bodySections: [
          { heading: 'Gap', markdown: 'the verify config is never threaded through.' },
          { heading: 'Provenance', markdown: 'wave hardening, row 3, iteration 1.' },
        ],
      }),
    ).toEqual({ kind: 'bare' });
  });

  // Regression guard: this new per-entry shape check must not swallow the
  // OLDER `bare-without-body` failure it now runs ahead of — well-formed
  // entries whose `markdown` is blank across the board are still a content
  // question, not a shape defect, and must still be spec-pinned unchanged.
  it('does NOT reclassify the existing all-blank-markdown case — `bare-without-body` still fires', () => {
    const err = rejectionOf({
      ...TITLE,
      bodySections: [
        { heading: 'Gap', markdown: '   ' },
        { heading: 'Provenance', markdown: '' },
      ],
    });
    expect(err.failure).toBe('bare-without-body');
  });

  // Same regression guard for the "one non-blank section is enough" case: a
  // well-formed entry with blank markdown alongside a well-formed entry with
  // real content must still classify as bare, not be rejected as malformed.
  it('does NOT reject a well-formed entry whose markdown happens to be blank, alongside a real one', () => {
    expect(
      classifyCreateInput({
        ...TITLE,
        bodySections: [
          { heading: 'Gap', markdown: '   ' },
          { heading: 'Provenance', markdown: 'wave hardening, row 3, iteration 1.' },
        ],
      }),
    ).toEqual({ kind: 'bare' });
  });

  // A DECORATED input's bodySections is a lighter-weight surface (optional,
  // additive prose) and is deliberately UNTOUCHED by this bare-only rule —
  // the pinned negative control for that lives in the `classifyCreateInput`
  // shape-classification describe block above. Re-asserted here, named to
  // this issue, so a future reader who lands on THIS describe block sees the
  // boundary too.
  it('a DECORATED input with a blank-markdown bodySections entry is still classified, not rejected (#530 does not touch decorated)', () => {
    const DECORATED: CreateInput = {
      title: 'A real slice',
      filingHint: 'a-real-slice',
      risk: 'mechanical',
      worker: 'background',
      files: ['src/x.ts'],
      blockedBy: 'none',
      acceptanceCriteria: [{ text: 'does the thing', checked: false }],
      bodySections: [{ heading: 'What to build', markdown: '   ' }],
    };
    expect(classifyCreateInput(DECORATED).kind).toBe('decorated');
  });
});

// ── #898: the acceptance-criteria ENTRY-SHAPE rule reaches `create` ──────────
//
// The LAYER specs for the create half of the defect #871 closed on `annotate`.
// #871's own guard call sites were exactly four, all `annotate` — the codec
// definition, the three stores — because the only lever inside its declared
// files was `serializeBody`, which `MarkdownFsStore` does not route through.
// A guard that fires on two stores out of three makes the remaining hole look
// closed, so the create half was carved out and filed instead of half-fixed.
//
// These cases call the CLASSIFIER directly, with no store and no CLI in the
// picture, because that is the claim: the rule is a property of
// `classifyCreateInput`, which every adapter runs as the first statement of
// `create()`, so every caller inherits it. The all-three-stores half is the
// conformance suite's; the CLI's exit code is `issue-store-cli.spec.ts`'.
describe('classifyCreateInput — the acceptanceCriteria entry-shape rule (#898)', () => {
  const DECORATED: CreateInput = {
    title: 'A real slice',
    filingHint: 'a-real-slice',
    risk: 'mechanical',
    worker: 'background',
    files: ['src/x.ts'],
    blockedBy: 'none',
    acceptanceCriteria: [{ text: 'does the thing', checked: false }],
  };

  /** A decorated input carrying `acceptanceCriteria` exactly as given (no typing in the way). */
  function withAc(acceptanceCriteria: unknown): CreateInput {
    return {
      ...DECORATED,
      acceptanceCriteria: acceptanceCriteria as { text: string; checked: boolean }[],
    };
  }

  /** Run the classifier and return the shape error it threw. */
  function shapeRejectionOf(input: CreateInput): AcceptanceCriteriaShapeError {
    try {
      classifyCreateInput(input);
    } catch (err) {
      expect(err).toBeInstanceOf(AcceptanceCriteriaShapeError);
      return err as AcceptanceCriteriaShapeError;
    }
    throw new Error('expected classifyCreateInput to reject, but it returned');
  }

  it('refuses THE live case — a bare string criterion — naming field, index and shape', () => {
    // Reproduced three times independently before this row was dispatched:
    // `create({ acceptanceCriteria: ['a bare string criterion'] })` returned
    // normally and read back `[{"text":"undefined","checked":false}]`.
    const err = shapeRejectionOf(withAc(['a bare string criterion']));
    expect(err.name).toBe('AcceptanceCriteriaShapeError');
    expect(err.field).toBe('acceptanceCriteria');
    expect(err.index).toBe(0);
    expect(err.received).toBe('string');
    expect(err.message).toContain('acceptanceCriteria');
    expect(err.message).toContain('entry 0');
    expect(err.message).toContain('a bare string criterion'); // it quotes what arrived
    expect(err.message).toContain('undefined'); // …and what it prevented
  });

  it('the refusal speaks for `create`, so the message names the call the caller made', () => {
    expect(() => classifyCreateInput(withAc(['x']))).toThrow(/^create:/);
  });

  it('refuses at all three levels the rule has — payload, entry, and the entry fields', () => {
    // The inherited strictness ruling (#871), re-asserted on the create side so
    // a laxer create-only predicate could never pass this file: the payload
    // must be an array, each entry must be an object, and `text`/`checked` must
    // each be of the declared type. A MISSING `checked` is REFUSED, never
    // defaulted to `false` — that is the ruling, not an accident of the code.
    expect(shapeRejectionOf(withAc('not an array at all')).index).toBe(-1);
    expect(shapeRejectionOf(withAc([null])).received).toBe('null');
    expect(shapeRejectionOf(withAc([42])).received).toBe('number');
    expect(shapeRejectionOf(withAc([{ checked: false }])).received).toBe('undefined');
    expect(shapeRejectionOf(withAc([{ text: 123, checked: false }])).received).toBe('number');
    expect(shapeRejectionOf(withAc([{ text: 'no checked flag' }])).received).toBe('undefined');
    // …and the index points at the FIRST offending entry, not at entry 0 by default.
    expect(
      shapeRejectionOf(withAc([{ text: 'fine', checked: false }, 'a string beside a good one']))
        .index,
    ).toBe(1);
  });

  it('is literally the same predicate `annotate` runs — same verdict, one context word apart', () => {
    // Acceptance criterion 3 in one assertion: there is no create-shaped copy
    // of the rule to drift from the annotate-shaped one. The two messages are
    // byte-identical once the leading context word is normalized away.
    const malformed: unknown[] = [
      ['a bare string criterion'],
      [null],
      [42],
      [{ checked: false }],
      [{ text: 123, checked: false }],
      [{ text: 'no checked flag' }],
      [{ text: 'fine', checked: false }, 'a string beside a good one'],
      'not an array at all',
    ];
    for (const acs of malformed) {
      const fromCreate = shapeRejectionOf(withAc(acs));
      let fromAnnotate: AcceptanceCriteriaShapeError | undefined;
      try {
        assertAcceptanceCriteriaShape(acs, 'annotate');
      } catch (err) {
        fromAnnotate = err as AcceptanceCriteriaShapeError;
      }
      expect(fromAnnotate).toBeInstanceOf(AcceptanceCriteriaShapeError);
      expect(fromCreate.field).toBe(fromAnnotate?.field);
      expect(fromCreate.index).toBe(fromAnnotate?.index);
      expect(fromCreate.received).toBe(fromAnnotate?.received);
      expect(fromCreate.message.replace(/^create:/, '')).toBe(
        fromAnnotate?.message.replace(/^annotate:/, ''),
      );
    }
  });

  it('costs a WELL-FORMED create nothing — the positive control', () => {
    expect(classifyCreateInput(DECORATED).kind).toBe('decorated');
    expect(
      classifyCreateInput(withAc([{ text: 'a', checked: false }, { text: 'b', checked: true }]))
        .kind,
    ).toBe('decorated');
    // `[]` is an explicit, empty checklist — a decision, not a malformed payload.
    expect(classifyCreateInput(withAc([])).kind).toBe('decorated');
    // An extra key beside the two required ones is not this rule's business.
    expect(
      classifyCreateInput(withAc([{ text: 'a', checked: false, note: 'extra' }])).kind,
    ).toBe('decorated');
  });

  it('leaves the BARE path untouched: an ABSENT acceptanceCriteria is the bare filing, not a malformed one', () => {
    // The bare arm requires the field absent, so the shape rule has nothing to
    // say there — and must not invent something to say. This is the cell that
    // fails if the guard ever moves ahead of the classification.
    expect(
      classifyCreateInput({
        title: 'Gate 8 ships inert',
        filingHint: 'gate-8-ships-inert',
        bodySections: [{ heading: 'Gap', markdown: 'the verify config is never threaded.' }],
      }),
    ).toEqual({ kind: 'bare' });
  });

  it('does NOT reclassify a HALF-WRITTEN Header-Block that happens to carry a malformed acceptanceCriteria', () => {
    // Deliberate precedence, pinned so it reads as a decision: the guard sits
    // on the DECORATED arm, after classification, so an input that is already
    // refused today keeps its existing verdict and its existing error class.
    // "Your header is half-written" is the coarser, more actionable claim about
    // such an input, and a consumer routing on `CreateInputError` for it keeps
    // working. The entry-shape rule still has nothing left to guard: the bare
    // arm forbids the field and this arm never reaches a write.
    let caught: unknown;
    try {
      classifyCreateInput({
        title: 'A real slice',
        filingHint: 'a-real-slice',
        acceptanceCriteria: ['a bare string criterion'] as unknown as {
          text: string;
          checked: boolean;
        }[],
      });
    } catch (err) {
      caught = err;
    }
    expect(caught).toBeInstanceOf(CreateInputError);
    expect((caught as CreateInputError).failure).toBe('header-block-half-written');
    expect(caught).not.toBeInstanceOf(AcceptanceCriteriaShapeError);
  });
});

// ── renderGoalUpdateBody — the mirror pass's ONE shared renderer (ADR-0046) ───
//
// LAYER specs, in the sense the classifier block above is: the renderer is called
// directly, with no store and no tracker in the picture, because that is where
// the claims live. `renderGoalUpdateBody` is pure — same facts, same bytes — so a
// published artifact's wording is a property of THIS function, and every adapter
// inherits it rather than re-deciding it.
//
// The frontier under test is built with the real `computeGoalFrontier` rather
// than hand-written, deliberately: the empty-membership case below is only
// interesting BECAUSE the derivation says `complete: true` there, and a
// hand-built literal could quietly assert against a rule the engine does not
// actually apply.
describe('renderGoalUpdateBody — an EMPTY goal publishes ONE reading, not two (#628)', () => {
  function member(overrides: Partial<GoalMemberFacts> & { id: string }): GoalMemberFacts {
    return {
      closed: false,
      claimed: false,
      eligible: true,
      unresolvedBlockers: [],
      ...overrides,
    };
  }

  it('a goal with ZERO members says "no members yet" and does NOT say the finish line was reached', () => {
    const frontier = computeGoalFrontier('goal-1', []);
    // The derivation is UNCHANGED and must stay so — an empty remainder is
    // empty, which is what stops the station from ever under-reporting. The fix
    // is a rendering decision on top of it, never an inversion of it.
    expect(frontier.complete).toBe(true);

    const body = renderGoalUpdateBody({ goalName: 'Milestone 3', frontier });

    expect(body).toContain(
      'This goal has no members yet, so there is nothing to report against it.',
    );
    // The contradiction this row exists to remove: the finish-line sentence, in
    // the same artifact as "no members yet", on the surface a stakeholder reads.
    expect(body).not.toContain(GOAL_UPDATE_EMPTY_FRONTIER_SENTENCE);
    // …and not by paraphrase either — no fragment of it survives.
    expect(body).not.toContain('the finish line has been reached');
    expect(body).not.toContain('Every member of this goal is closed');
    // The anchor itself is still whole: this gates ONE sentence, not the pass.
    expect(body).toContain(GOAL_UPDATE_ANCHOR_HEADING);
    expect(body.trimEnd().endsWith(GOAL_UPDATE_PROVENANCE_LINE)).toBe(true);
  });

  it('a goal WITH members, every one of them closed, publishes the sentence VERBATIM — and still hands the act back', () => {
    const frontier = computeGoalFrontier('goal-1', [
      member({ id: 'm-1', closed: true }),
      member({ id: 'm-2', closed: true }),
    ]);
    expect(frontier.complete).toBe(true);

    const body = renderGoalUpdateBody({ goalName: 'Milestone 3', frontier });

    // VERBATIM — the constant, not a paraphrase of it.
    expect(body).toContain(GOAL_UPDATE_EMPTY_FRONTIER_SENTENCE);
    // The half that makes it accounting rather than permission: closing the
    // container is named as the OPERATOR's act, in the published bytes.
    expect(body).toContain('is the Operator’s act in the tracker');
    expect(body).toContain('does not declare it reached');
    // …and this reading is NOT the empty-membership one.
    expect(body).not.toContain('no members yet');
    expect(body).toContain('2 of 2 members are done.');
  });

  it('a goal with members still OPEN says neither — the two sentences are mutually exclusive, not merely ordered', () => {
    const frontier = computeGoalFrontier('goal-1', [
      member({ id: 'm-1', closed: true }),
      member({ id: 'm-2' }),
    ]);
    expect(frontier.complete).toBe(false);

    const body = renderGoalUpdateBody({ goalName: 'Milestone 3', frontier });

    expect(body).not.toContain('no members yet');
    expect(body).not.toContain(GOAL_UPDATE_EMPTY_FRONTIER_SENTENCE);
    expect(body).toContain('1 of 2 members are done. Still open: 1 ready to pick up.');
  });
});

// ── the blocker rendering — all THREE forms, pinned (#628) ───────────────────
//
// `GoalBlocker` has two SPELLINGS (an `IssueRef`, a bare member id) and three
// renderings, because the `IssueRef` arm splits on whether the ref carries a
// slug. The helper is module-private, so it is exercised where it actually
// matters: through the rendered update body a reader receives.
describe('renderGoalUpdateBody — every blocker spelling reaches the anchor (#628)', () => {
  /** One `blocked` member carrying exactly the blockers under test. */
  function blockedOn(unresolvedBlockers: GoalMemberFacts['unresolvedBlockers']) {
    return computeGoalFrontier('goal-1', [
      { id: 'm-1', closed: false, claimed: false, eligible: true, unresolvedBlockers },
    ]);
  }

  it('an IssueRef WITH a slug renders as `slug#issue`', () => {
    const body = renderGoalUpdateBody({
      goalName: 'Milestone 3',
      frontier: blockedOn([{ slug: 'flotilla', issue: 596 }]),
      identities: [{ id: 'm-1', name: 'The blocked one' }],
    });
    expect(body).toContain('waiting on flotilla#596');
  });

  it('an IssueRef WITHOUT a slug renders as `#issue` — never a fabricated slug', () => {
    const body = renderGoalUpdateBody({
      goalName: 'Milestone 3',
      frontier: blockedOn([{ issue: 596 }]),
      identities: [{ id: 'm-1', name: 'The blocked one' }],
    });
    expect(body).toContain('waiting on #596');
    // The negative half: nothing invented a slug to put in front of it.
    expect(body).not.toMatch(/waiting on \S+#596/);
  });

  it('a BARE member id renders as itself — a project UUID has no `#n` spelling', () => {
    const body = renderGoalUpdateBody({
      goalName: 'Milestone 3',
      frontier: blockedOn(['3f8a1c7e-0000-4a2b-9c11-abcdef012345']),
      identities: [{ id: 'm-1', name: 'The blocked one' }],
    });
    expect(body).toContain('waiting on 3f8a1c7e-0000-4a2b-9c11-abcdef012345');
    // Verbatim, not decorated: no `#` was bolted onto an opaque id.
    expect(body).not.toContain('#3f8a1c7e');
  });

  it('the three spellings coexist on ONE member, comma-joined in order', () => {
    const body = renderGoalUpdateBody({
      goalName: 'Milestone 3',
      frontier: blockedOn([{ slug: 'flotilla', issue: 596 }, { issue: 627 }, 'prj-7']),
      identities: [{ id: 'm-1', name: 'The blocked one' }],
    });
    expect(body).toContain('waiting on flotilla#596, #627, prj-7');
  });

  it('a member that is NOT blocked renders no waiting clause at all — the non-vacuity control', () => {
    const body = renderGoalUpdateBody({
      goalName: 'Milestone 3',
      frontier: computeGoalFrontier('goal-1', [
        { id: 'm-1', closed: false, claimed: false, eligible: true, unresolvedBlockers: [] },
      ]),
      identities: [{ id: 'm-1', name: 'The unblocked one' }],
    });
    expect(body).not.toContain('waiting on');
  });
});
