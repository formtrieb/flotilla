// ── annotate's filesAdd (ADR-0054 decision 5) — the pure layer the stores share
describe('validateAnnotatePatch — files and filesAdd are one or the other', () => {
  it('refuses a patch carrying both, with a typed error that names both keys', () => {
    expect(() => validateAnnotatePatch({ files: ['a.ts'], filesAdd: ['b.ts'] })).toThrow(
      AnnotatePatchError,
    );
    expect(() => validateAnnotatePatch({ files: [], filesAdd: [] })).toThrow(/`files`.*`filesAdd`/);
  });

  it('refuses a filesAdd that is not an array of non-blank strings', () => {
    for (const bad of ['a.ts', [42], [''], ['  '], [null]]) {
      expect(() => validateAnnotatePatch({ filesAdd: bad as unknown as string[] })).toThrow(
        AnnotatePatchError,
      );
    }
  });

  it('accepts either key alone, an empty filesAdd, and a patch with neither', () => {
    expect(() => validateAnnotatePatch({ files: ['a.ts'] })).not.toThrow();
    expect(() => validateAnnotatePatch({ filesAdd: ['a.ts'] })).not.toThrow();
    expect(() => validateAnnotatePatch({ filesAdd: [] })).not.toThrow();
    expect(() => validateAnnotatePatch({ risk: 'mechanical' })).not.toThrow();
  });
});

